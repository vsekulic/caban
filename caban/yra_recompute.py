def discover_sessions(
    roots=None,
    mouse_pattern: str = sq.MOUSE_DIR_PATTERN,
    minian_dir_overrides: Optional[dict] = None,
) -> List[sq.SessionWork]:
    """Find every session whose ``YrA`` can be recomputed.

    A session qualifies when it has numbered ``.avi`` files *and* a complete
    ``minian_crossreg*`` -- this pipeline recomputes a residual against footprints
    that already exist, so a session without them is not work here (it is work for
    the CNMF-E pipeline instead). Sessions with two complete Minian outputs raise
    unless pinned through ``minian_dir_overrides``; see
    :func:`caban.session_queue.resolve_minian_dir`.
    """
    candidates = sq.scan_sessions(roots=roots, mouse_pattern=mouse_pattern)
    items = []
    for candidate in candidates:
        if not candidate.n_avi or not candidate.complete_minian_dirs:
            continue
        minian_dir = sq.resolve_minian_dir(candidate, minian_dir_overrides)
        items.append(sq.SessionWork(
            candidate=candidate,
            minian_dir=minian_dir,
            output_dir=minian_dir,
        ))
    print("  -> {} of these are work for the YrA recompute".format(len(items)))
    return items


def output_present(item: sq.SessionWork) -> bool:
    """Cheap "looks finished" test for one item; see :func:`sq.output_present`."""
    return sq.output_present(item, SIDECAR_NAME, OUTPUT_ARRAY_NAME)


def next_pending(items: List[sq.SessionWork]) -> Optional[sq.SessionWork]:
    """The first session that is not already done, or ``None`` when all are.

    Position is re-derived from what is on disk on every call rather than held in a
    generator, so this survives a kernel restart and lands on the next session by
    itself once the current one finishes.
    """
    return sq.next_pending(items, SIDECAR_NAME, OUTPUT_ARRAY_NAME)


def _status_columns(item: sq.SessionWork, record: dict) -> dict:
    """The numbers that make this pipeline's queue readable at a glance.

    ``r_zero_overlap_median`` is the per-session gate: those units have ``YrA_i``
    determined by the replayed movie and their own footprint alone, so a value that
    is not ~0.999999 means that session's ``Y`` did not replay
    (`plans/yra_recompute_plan.md` §13.4).
    """
    report = record.get("report") or {}
    against_old = report.get("vs_old_YrA") or {}
    corr = against_old.get("corr") or {}
    by_overlap = against_old.get("corr_by_footprint_overlap") or []
    no_overlap = next((e for e in by_overlap if e["overlap"] == "none"), {})
    return {
        "has_old_YrA": item.existing_yra_path is not None,
        "has_saved_Y": item.saved_movie_path is not None,
        "n_units": report.get("n_units"),
        "n_frames": report.get("n_frames"),
        "r_vs_old_median": corr.get("median"),
        "r_zero_overlap_median": no_overlap.get("median"),
    }


def queue_status(items: List[sq.SessionWork]) -> pd.DataFrame:
    """One row per session: what it is, and whether it still needs doing."""
    frame = sq.queue_frame(items, SIDECAR_NAME, OUTPUT_ARRAY_NAME, _status_columns)
    order = ["mouse", "day", "session", "n_avi", "has_old_YrA", "has_saved_Y", "done",
             "n_units", "n_frames", "r_vs_old_median", "r_zero_overlap_median"]
    return frame[[c for c in order if c in frame.columns]]


def describe_item(item: sq.SessionWork) -> None:
    """Print what a work item is, before anything is computed."""
    print("{}".format(item.label))
    print("  videos      : {} .avi in {}".format(item.n_avi, item.session_dir))
    print("  minian      : {}".format(os.path.basename(item.minian_dir)))
    print("  old YrA     : {}".format(item.existing_yra_path or "none -- nothing to compare against"))
    print("  saved Y     : {}".format(item.saved_movie_path or "none"))
    print("  output      : {}".format(item.output_dir))
    print("  del_frames  : {} (from the notebook corpus)".format(
        notebook_del_frames(item.session_dir) or "[]"))
    print("  done        : {}".format(output_present(item)))


def preview_item(item: sq.SessionWork, **kwargs) -> dict:
    """Dry-run one work item: resolve and cross-check its inputs, compute nothing."""
    describe_item(item)
    print()
    return run_item(item, dry_run=True, **kwargs)


def run_item(
    item: sq.SessionWork,
    frame_chunk: int = DEFAULT_FRAME_CHUNK,
    dry_run: bool = False,
    force: bool = False,
) -> dict:
    """Recompute one work item, looking its ``del_frames`` up from the corpus table."""
    return recompute_session_yra(
        session_dir=item.session_dir,
        minian_dir=item.minian_dir,
        output_dir=item.output_dir,
        del_frames_notebook=notebook_del_frames(item.session_dir),
        existing_yra_path=item.existing_yra_path,
        saved_movie_path=item.saved_movie_path,
        frame_chunk=frame_chunk,
        dry_run=dry_run,
        force=force,
    )


def run_all(items: List[sq.SessionWork], stop_on_error: bool = True, **kwargs) -> List[dict]:
    """Work through the queue serially, printing each report before the next session."""
    return sq.run_queue(items, run_item, stop_on_error=stop_on_error, **kwargs)


