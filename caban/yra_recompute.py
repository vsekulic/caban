"""Recompute Minian's ``YrA`` residual traces from the saved footprints and a replayed movie.

Why this exists
---------------
The ``YrA.zarr`` that Minian exported for every session was written by a second
pipeline run, roughly a year after the run that produced the ``A``/``C``/``S`` the
rest of ``caban`` depends on.  Its ``unit_id`` is sorted ascending while ``S``'s is
not, so row *i* of the exported ``YrA`` is generally a different cell from row *i*
of ``S``; in eight mice the two runs additionally disagree about a handful of
threshold-marginal cells.  ``sessions.Session._align_YrA_to_S_units`` repairs this
in memory at load time.  Recomputing ``YrA`` against the footprints that are
actually in ``A.zarr`` removes the need for the repair: ``compute_trace`` stamps
``A``'s ``unit_id`` straight onto its output, and ``A``'s ``unit_id`` equals
``S``'s elementwise.

See ``plans/yra_recompute_plan.md`` for the full argument, the evidence, and the
verification scheme this module implements.

What it does
------------
``YrA`` needs the motion-corrected movie ``Y``, which was never saved (except for
G10's conditioning session).  ``Y`` is therefore regenerated by replaying the
preprocessing chain recorded in ``pipeline-WORKING-TFC_cond-*.ipynb``::

    varr     = load_videos(...)                       # raw .avi frames, uint8
    varr     = drop del_frames                        # per-session, usually none
    varr_ref = varr - varr.min("frame")               # glow removal
    varr_ref = denoise(varr_ref, "median", ksize=5)
    varr_ref = remove_background(varr_ref, "tophat", wnd=15)
    Y        = apply_transform(varr_ref, motion, fill=0).astype(float)
    YrA      = compute_trace(Y, A, b, C, f)

``Y`` is never materialised to disk: at 608x608x~26k float64 it is ~77 GB per
session.  Every step above is a lazy dask operation and ``compute_trace``
consumes ``Y`` through ``tensordot``, so the chain streams from the ``.avi``
files.

Vendored Minian code
--------------------
The five operations above come from the Minian fork at
``~/code/minian_vsekulic`` (commit :data:`MINIAN_SOURCE_COMMIT`).  They
are vendored here rather than installed: Minian pins numpy 1.20 against this
environment's 2.4, so installing it would mean a second environment for five
functions, four of which are thin wrappers around cv2 and SimpleITK.  Each
vendored function carries a provenance comment naming its Minian source file, and
every deviation from the original is called out in that comment.
"""

