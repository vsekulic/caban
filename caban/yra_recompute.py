def probe_video(fname: str) -> dict:
    """Return width, height and frame count of a video, via ``ffprobe``.

    Vendored behaviour of ``ffmpeg.probe`` as used by ``minian/utilities.py::
    load_avi_lazy``.  Deviation: the ``ffmpeg-python`` wrapper is not installed in
    this environment, so ``ffprobe`` is invoked directly.  The fields read are the
    same three the Minian code reads.
    """
    proc = subprocess.run(
        [
            "ffprobe", "-v", "error", "-select_streams", "v:0",
            "-show_entries", "stream=width,height,nb_frames",
            "-of", "json", fname,
        ],
        capture_output=True,
        check=True,
    )
    streams = json.loads(proc.stdout)["streams"]
    if len(streams) != 1:
        raise ValueError(
            "expected exactly one video stream in {}, found {}".format(fname, len(streams))
        )
    info = streams[0]
    return {
        "width": int(info["width"]),
        "height": int(info["height"]),
        "n_frames": int(info["nb_frames"]),
    }


def load_avi_ffmpeg(fname: str, h: int, w: int, f: int) -> np.ndarray:
    """Load an avi video using ``ffmpeg``.

    Vendored from ``minian/utilities.py::load_avi_ffmpeg``.  Deviation: the
    ``ffmpeg-python`` wrapper is replaced by the equivalent direct invocation --
    ``ffmpeg.input(fname).video.output("pipe:", format="rawvideo",
    pix_fmt="gray").run(capture_stdout=True)`` compiles to exactly this argument
    list.  The reshape and dtype are unchanged.
    """
    proc = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", fname, "-map", "0:v",
         "-f", "rawvideo", "-pix_fmt", "gray", "pipe:"],
        capture_output=True,
        check=True,
    )
    expected = f * h * w
    if len(proc.stdout) != expected:
        raise ValueError(
            "{}: ffmpeg returned {} bytes, expected {} for {} frames of {}x{}".format(
                fname, len(proc.stdout), expected, f, h, w
            )
        )
    return np.frombuffer(proc.stdout, np.uint8).reshape(f, h, w)


def load_avi_lazy(fname: str) -> darr.Array:
    """Lazily load an avi video as a single delayed task.

    Vendored from ``minian/utilities.py::load_avi_lazy``.  Deviation: dimensions
    come from :func:`probe_video` instead of ``ffmpeg.probe``.
    """
    info = probe_video(fname)
    return darr.from_delayed(
        dask.delayed(load_avi_ffmpeg)(
            fname, info["height"], info["width"], info["n_frames"]
        ),
        dtype=np.uint8,
        shape=(info["n_frames"], info["height"], info["width"]),
    )


def _video_list(vpath: str, pattern: str, exclude=()) -> List[str]:
    """The videos matching ``pattern``, natsorted, minus ``exclude`` (basenames).

    Every name in ``exclude`` must exist, so a stale exclusion is an error, not a no-op.
    """
    names = [v for v in os.listdir(vpath) if re.search(pattern, v)]
    missing = [e for e in exclude if e not in names]
    if missing:
        raise FileNotFoundError("videos to exclude not found in {}: {}".format(vpath, missing))
    vlist = natsorted([os.path.join(vpath, v) for v in names if v not in exclude])
    if not vlist:
        raise FileNotFoundError(
            "No data with pattern {} found in the specified folder {}".format(pattern, vpath)
        )
    return vlist


def load_videos(
    vpath: str,
    pattern=r"msCam[0-9]+\.avi$",
    dtype=np.float64,
    downsample=None,
    downsample_strategy="subset",
    exclude=(),
) -> xr.DataArray:
    """Load and concatenate the videos in a folder into an ``xr.DataArray``.

    Vendored from ``minian/utilities.py::load_videos``.  Deviations: the ``.tif``
    branch and the ``post_process`` hook are dropped (this pipeline uses neither,
    and an unsupported extension still raises), and the trailing
    ``custom_arr_optimize`` dask-graph rewrite is dropped -- it is a scheduler
    optimisation with no effect on values.  Addition: ``exclude`` drops named files
    (see :data:`UNUSED_VIDEOS`).
    """
    vpath = os.path.normpath(vpath)
    vlist = _video_list(vpath, pattern, exclude)
    print("loading {} videos in folder {}{}".format(
        len(vlist), vpath, " (excluding {})".format(list(exclude)) if exclude else ""))

    file_extension = os.path.splitext(vlist[0])[1]
    if file_extension not in (".avi", ".mkv"):
        raise ValueError("Extension not supported: {}".format(file_extension))

    varr_list = [load_avi_lazy(v) for v in vlist]
    varr = darr.concatenate(varr_list, axis=0)
    varr = xr.DataArray(
        varr,
        dims=["frame", "height", "width"],
        coords=dict(
            frame=np.arange(varr.shape[0]),
            height=np.arange(varr.shape[1]),
            width=np.arange(varr.shape[2]),
        ),
    )
    if dtype:
        varr = varr.astype(dtype)
    if downsample:
        if downsample_strategy == "mean":
            varr = varr.coarsen(**downsample, boundary="trim", coord_func="min").mean()
        elif downsample_strategy == "subset":
            varr = varr.isel(**{d: slice(None, None, w) for d, w in downsample.items()})
        else:
            raise NotImplementedError("unrecognized downsampling strategy")
    return varr.rename("fluorescence")


def denoise(varr: xr.DataArray, method: str, **kwargs) -> xr.DataArray:
    """Denoise the movie frame by frame.

    Vendored verbatim from ``minian/preprocessing.py::denoise``, restricted to the
    methods this pipeline uses.  The ``anisotropic`` branch is dropped because it
    needs ``medpy``, which is not installed; an unrecognised method still raises.
    """
    if method == "gaussian":
        func = cv2.GaussianBlur
    elif method == "median":
        func = cv2.medianBlur
    elif method == "bilateral":
        func = cv2.bilateralFilter
    else:
        raise NotImplementedError("denoise method {} not understood".format(method))
    res = xr.apply_ufunc(
        func,
        varr,
        input_core_dims=[["height", "width"]],
        output_core_dims=[["height", "width"]],
        vectorize=True,
        dask="parallelized",
        output_dtypes=[varr.dtype],
        kwargs=kwargs,
    )
    res = res.astype(varr.dtype)
    return res.rename(varr.name + "_denoised")


def remove_background_perframe(fm: np.ndarray, method: str, wnd: int, selem: np.ndarray) -> np.ndarray:
    """Remove background from a single frame.

    Vendored verbatim from ``minian/preprocessing.py::remove_background_perframe``.
    """
    if method == "uniform":
        raise NotImplementedError(
            "the uniform branch needs scipy.ndimage.uniform_filter and is not used by "
            "this pipeline; parameters recorded in the notebook are tophat/wnd=15"
        )
    elif method == "tophat":
        return cv2.morphologyEx(fm, cv2.MORPH_TOPHAT, selem)
    raise NotImplementedError("background removal method {} not understood".format(method))


def remove_background(varr: xr.DataArray, method: str, wnd: int) -> xr.DataArray:
    """Remove background from a video, frame by frame.

    Vendored verbatim from ``minian/preprocessing.py::remove_background``.
    """
    selem = disk(wnd)
    res = xr.apply_ufunc(
        remove_background_perframe,
        varr,
        input_core_dims=[["height", "width"]],
        output_core_dims=[["height", "width"]],
        vectorize=True,
        dask="parallelized",
        output_dtypes=[varr.dtype],
        kwargs=dict(method=method, wnd=wnd, selem=selem),
    )
    res = res.astype(varr.dtype)
    return res.rename(varr.name + "_subtracted")


def transform_perframe(fm: np.ndarray, tx_coef: np.ndarray, fill=0, param=None) -> np.ndarray:
    """Apply a rigid translation to a single frame, with linear subpixel interpolation.

    Vendored from ``minian/motion_correction.py::transform_perframe``, restricted
    to the rigid-translation branch (``motion.zarr`` has dims ``(frame,
    shift_dim)``, so the BSpline branch is unreachable here and its ``param``
    argument is kept only so the signature matches).  The interpolation is the one
    part of the replay with real substance -- integer shifting instead of
    ``sitkLinear`` would silently change ``Y``.
    """
    if np.ndim(tx_coef) > 1:
        raise NotImplementedError(
            "non-rigid (BSpline) motion is not used by this pipeline; motion.zarr "
            "carries per-frame (height, width) shifts"
        )
    tx = sitk.TranslationTransform(2, -tx_coef[::-1])
    fm = sitk.GetImageFromArray(fm)
    fm = sitk.Resample(fm, fm, tx, sitk.sitkLinear, fill)
    return sitk.GetArrayFromImage(fm)


def apply_transform(varr: xr.DataArray, trans: xr.DataArray, fill=0) -> xr.DataArray:
    """Apply the estimated motion to correct a movie.

    Vendored from ``minian/motion_correction.py::apply_transform``, restricted to
    the rigid branch (see :func:`transform_perframe`).
    """
    if "grid0" in trans.dims:
        raise NotImplementedError(
            "non-rigid (BSpline) motion is not used by this pipeline"
        )
    sh_dim = trans.coords["shift_dim"].values.tolist()
    varr_sh = xr.apply_ufunc(
        transform_perframe,
        varr.chunk({d: -1 for d in sh_dim}),
        trans,
        input_core_dims=[sh_dim, ["shift_dim"]],
        output_core_dims=[sh_dim],
        vectorize=True,
        dask="parallelized",
        kwargs={"fill": fill, "param": None},
        output_dtypes=[varr.dtype],
    )
    return varr_sh


def compute_trace(
    Y: xr.DataArray, A: xr.DataArray, b: xr.DataArray, C: xr.DataArray, f: xr.DataArray
) -> xr.DataArray:
    """Compute the residual traces ``YrA`` for each cell.

    Vendored from ``minian/cnmf.py::compute_trace``.  Deviation: the trailing
    ``custom_arr_optimize`` / ``da.optimize`` block is dropped -- it renames and
    inlines dask graph keys and has no effect on values.  The arithmetic, its
    order and its sparsity are unchanged.

    ``YrA_i = max(0, C_i + (<Ybs, A_i> - sum_j C_j <A_i, A_j>) / <A_i, A_i>)``.
    Note that the ``j == i`` term of the sum cancels ``C_i`` exactly, so ``YrA``
    depends on ``C`` only through the crosstalk of *overlapping* footprints.
    """
    fms = Y.coords["frame"]
    uid = A.coords["unit_id"]
    Y = Y.data
    A = darr.from_array(A.data.map_blocks(sparse.COO).compute(), chunks=-1)
    C = C.data.map_blocks(sparse.COO).T
    b = (
        b.fillna(0)
        .data.map_blocks(sparse.COO)
        .reshape((1, Y.shape[1], Y.shape[2]))
        .compute()
    )
    f = f.fillna(0).data.reshape((-1, 1))
    AtA = darr.tensordot(A, A, axes=[(1, 2), (1, 2)]).compute()
    A_norm = (
        (1 / (A ** 2).sum(axis=(1, 2)))
        .map_blocks(
            lambda a: sparse.diagonalize(sparse.COO(a)), chunks=(A.shape[0], A.shape[0])
        )
        .compute()
    )
    B = darr.tensordot(f, b, axes=[(1), (0)])
    Y = Y - B
    YtA = darr.tensordot(Y, A, axes=[(1, 2), (1, 2)])
    YtA = darr.dot(YtA, A_norm)
    CtA = darr.dot(C, AtA)
    CtA = darr.dot(CtA, A_norm)
    YrA = (YtA - CtA + C).clip(0)
    YrA = xr.DataArray(
        YrA,
        dims=["frame", "unit_id"],
        coords={"frame": fms, "unit_id": uid},
    )
    return YrA.transpose("unit_id", "frame")


