def recompute_session_yra(
    session_dir: str,
    minian_dir: str,
    output_dir: str,
    del_frames_notebook: list,
    existing_yra_path: Optional[str] = None,
    saved_movie_path: Optional[str] = None,
    frame_chunk: int = DEFAULT_FRAME_CHUNK,
    dry_run: bool = False,
    force: bool = False,
) -> dict:
    """Recompute one session's ``YrA`` and verify it.

    Parameters
    ----------
    session_dir
        The session's ``Miniscope`` folder, holding the numbered ``.avi`` files.
    minian_dir
        The folder holding ``A``/``C``/``b``/``f``/``motion`` ``.zarr`` for this
        session -- normally ``<session_dir>/minian_crossreg*``.
    output_dir
        Where ``YrA_recomputed.zarr`` and its sidecar are written.  The existing
        ``YrA.zarr`` is never touched.
    del_frames_notebook
        The frames the pipeline notebook dropped for this session.  Cross-checked
        against the value derived from the saved ``frame`` coordinate; a
        disagreement is a hard failure.
    existing_yra_path
        The exported ``YrA.zarr`` to compare against, or ``None`` for the sessions
        that never had one.
    saved_movie_path
        Optional ``minian_intermediate/Y_fm_chk.zarr``, present only for G10's
        conditioning session.  When given, the replayed ``Y`` is checked against it.
    dry_run
        Report the inputs and the derived ``del_frames``, then stop without
        computing or writing anything.
    force
        Recompute even when the sidecar says this session is already done.
    """
    A = open_minian_array(minian_dir, "A")
    C = open_minian_array(minian_dir, "C")
    b = open_minian_array(minian_dir, "b")
    f = open_minian_array(minian_dir, "f")
    motion = open_minian_array(minian_dir, "motion")
    # A NaN shift moves every pixel out of frame: the replayed Y would be all zeros and
    # so would YrA. Checked before `completed_run`, so an output already written from
    # such a motion is not accepted either. Found 2026-09-26 in two G05 TFC_test_B
    # production sessions whose saved motion.zarr is NaN in every frame.
    nan_frames = int(np.isnan(motion.values).any(axis=1).sum())
    if nan_frames:
        raise ValueError(
            "{}: motion.zarr is NaN in {} of {} frames, so Y cannot be replayed from it "
            "(it would be all zeros, and so would YrA). Production's movie was not: its "
            "C and max_proj are nonzero, so the saved motion is not the one that was "
            "applied.".format(minian_dir, nan_frames, motion.sizes["frame"]))
    S_unit_id = np.asarray(open_minian_array(minian_dir, "S").coords["unit_id"].values)

    A_unit_id = np.asarray(A.coords["unit_id"].values)
    if not np.array_equal(A_unit_id, S_unit_id):
        raise ValueError(
            "A.zarr and S.zarr disagree about unit_id in {}; the whole recompute rests "
            "on them being equal elementwise".format(minian_dir)
        )
    footprint_energy = (A ** 2).sum(["height", "width"]).compute().values
    if not (footprint_energy > 0).all():
        empty = A_unit_id[footprint_energy <= 0].tolist()
        raise ValueError(
            "units {} have all-zero footprints in A.zarr; compute_trace would divide "
            "by zero normalising them".format(empty)
        )

    if not force and not dry_run:
        done = completed_run(output_dir, minian_dir, S_unit_id)
        if done is not None:
            print("{} is already recomputed from these inputs ({}); nothing to do.".format(
                os.path.join(output_dir, OUTPUT_ARRAY_NAME), done["written_utc"]))
            print(format_report(done["report"]))
            return done

    excluded_videos = unused_videos(session_dir)
    n_video_frames = count_video_frames(session_dir, PARAM_LOAD_VIDEOS["pattern"], excluded_videos)
    del_frames_derived = derive_deleted_frames(n_video_frames, C.frame.values)

    print("session      : {}".format(session_dir))
    print("minian output: {}".format(minian_dir))
    print("units        : {}   frames in C: {}   frames in videos: {}".format(
        len(S_unit_id), C.sizes["frame"], n_video_frames))
    if excluded_videos:
        print("unused videos: {} (never read by production; UNUSED_VIDEOS)".format(excluded_videos))
    print("del_frames   : derived {}  |  notebook {}".format(
        del_frames_derived or "[]", list(del_frames_notebook) or "[]"))
    if dry_run:
        print("DRY_RUN: stopping before the replay.")
        return {"dry_run": True, "del_frames_derived": del_frames_derived,
                "del_frames_notebook": list(del_frames_notebook)}

    Y = replay_motion_corrected_movie(session_dir, motion, del_frames_derived, frame_chunk,
                                      exclude_videos=excluded_videos)

    movie_check = None
    if saved_movie_path:
        print("comparing the replayed Y against {}".format(saved_movie_path))
        movie_check = compare_replayed_movie(Y, saved_movie_path)
        print("  {}".format(movie_check))

    print("computing YrA over {} units x {} frames".format(len(S_unit_id), C.sizes["frame"]))
    YrA_new = compute_trace(
        Y, A, b, C.chunk({"unit_id": -1, "frame": frame_chunk}), f.chunk({"frame": frame_chunk})
    ).compute()

    YrA_old = None
    if existing_yra_path:
        YrA_old = xr.open_zarr(existing_yra_path, consolidated=False)["YrA"].compute()
    report = check_and_report(
        YrA_new, S_unit_id, C.compute(), YrA_old, del_frames_derived,
        list(del_frames_notebook), footprint_overlap_ratio(A),
    )
    if report["corr_C_vs_new"]["n"] == 0:
        raise ValueError(
            "{}: corr(C, YrA_new) is undefined for every unit -- the recomputed YrA is "
            "constant (all-zero clip floor {:.3f}); not writing it".format(
                minian_dir, report["clip_floor_fraction"]["overall"]))
    if movie_check is not None:
        report["replayed_Y_vs_saved_Y_fm_chk"] = movie_check

    output_path = os.path.join(output_dir, OUTPUT_ARRAY_NAME)
    if existing_yra_path and os.path.realpath(output_path) == os.path.realpath(existing_yra_path):
        raise ValueError(
            "refusing to write over the existing export at {}".format(existing_yra_path)
        )
    os.makedirs(output_dir, exist_ok=True)
    out = YrA_new.rename("YrA")
    for name in ("animal", "session"):
        if name in C.coords:
            out = out.assign_coords({name: C.coords[name]})
    out.to_dataset().to_zarr(output_path, mode="w", zarr_format=2, consolidated=False)
    print("wrote {}".format(output_path))

    record = {
        "written_utc": datetime.now(timezone.utc).isoformat(),
        "minian_source_repo": MINIAN_SOURCE_REPO,
        "minian_source_commit": MINIAN_SOURCE_COMMIT,
        "session_dir": session_dir,
        "minian_dir": minian_dir,
        "existing_yra_path": existing_yra_path,
        "saved_movie_path": saved_movie_path,
        "param_load_videos": {k: str(v) for k, v in PARAM_LOAD_VIDEOS.items()},
        "param_denoise": PARAM_DENOISE,
        "param_background_removal": PARAM_BACKGROUND_REMOVAL,
        "frame_chunk": frame_chunk,
        "del_frames": del_frames_derived,
        "unused_videos": excluded_videos,
        "n_video_frames": n_video_frames,
        "input_hashes": {
            name: hash_zarr_store(os.path.join(minian_dir, name + ".zarr"))
            for name in HASHED_INPUTS
        },
        "report": report,
        "complete": True,
    }
    write_sidecar(output_dir, record)
    print(format_report(report))
    return record
