def open_minian_array(minian_dir: str, name: str) -> xr.DataArray:
    """Read one Minian ``<name>.zarr`` store as a dask-backed ``xr.DataArray``.

    ``zarr.load`` -- what ``sessions.py`` uses -- raises ``NotImplementedError`` on
    groups under zarr 3.x, and would give eager numpy anyway.  The replay needs
    the arrays lazy.
    """
    path = os.path.join(minian_dir, name + ".zarr")
    if not os.path.isdir(path):
        raise FileNotFoundError("no {} in {}".format(name + ".zarr", minian_dir))
    return xr.open_zarr(path, consolidated=False)[name]


def derive_deleted_frames(n_video_frames: int, frame_coord: np.ndarray) -> list:
    """Recover the per-session ``del_frames`` from a saved ``frame`` coordinate.

    The ``frame`` coordinate of ``C.zarr`` / ``motion.zarr`` is the post-deletion
    frame set, so the frames the notebook dropped are exactly those missing from
    it.  This is the independent derivation that :file:`plans/yra_recompute_plan.md`
    6.1 asks for: it is cross-checked against the notebook value rather than
    either being trusted alone.
    """
    frame_coord = np.asarray(frame_coord)
    if frame_coord.ndim != 1:
        raise ValueError("frame coordinate must be 1-D, got shape {}".format(frame_coord.shape))
    if len(np.unique(frame_coord)) != len(frame_coord):
        raise ValueError("frame coordinate has duplicate entries")
    if frame_coord.min() < 0 or frame_coord.max() >= n_video_frames:
        raise ValueError(
            "frame coordinate spans [{}, {}], outside the {} frames present in the "
            "videos -- the video folder and the Minian output do not belong together".format(
                frame_coord.min(), frame_coord.max(), n_video_frames
            )
        )
    return sorted(set(range(n_video_frames)) - set(frame_coord.tolist()))


def count_video_frames(video_dir: str, pattern: str, exclude=()) -> int:
    """Total frame count over the ``.avi`` files the replay will read."""
    return sum(probe_video(v)["n_frames"] for v in _video_list(video_dir, pattern, exclude))


def replay_motion_corrected_movie(
    video_dir: str,
    motion: xr.DataArray,
    del_frames: list,
    frame_chunk: int = DEFAULT_FRAME_CHUNK,
    exclude_videos=(),
) -> xr.DataArray:
    """Regenerate ``Y``: the motion-corrected, background-removed movie.

    Reproduces the preprocessing cells of ``pipeline-WORKING-TFC_cond-*.ipynb`` in
    order.  The result is lazy -- nothing but the per-pixel minimum used for glow
    removal is computed here.
    """
    varr = load_videos(video_dir, exclude=exclude_videos, **PARAM_LOAD_VIDEOS)
    if del_frames:
        varr = varr.where(~varr.frame.isin(del_frames), drop=True).astype("uint8")
    # The notebook's `subset = dict(frame=slice(0, None))` and `subset_mc = None`,
    # so `varr_ref = varr.sel(subset)` keeps every frame and every pixel.
    varr_ref = varr.chunk({"frame": frame_chunk, "height": -1, "width": -1})

    # Compare the frame values, not the coordinate DataArrays: the Minian arrays
    # carry scalar `animal`/`session` coords that ride along on `.frame` and make
    # `DataArray.equals` False for frame sets that are in fact identical.
    if not np.array_equal(varr_ref.frame.values, motion.frame.values):
        raise ValueError(
            "replayed movie has {} frames {}..{} but motion.zarr has {} frames {}..{}; "
            "del_frames is wrong or the video folder does not match the Minian output".format(
                varr_ref.sizes["frame"], int(varr_ref.frame[0]), int(varr_ref.frame[-1]),
                motion.sizes["frame"], int(motion.frame[0]), int(motion.frame[-1]),
            )
        )

    print("computing per-pixel minimum over {} frames for glow removal".format(varr_ref.sizes["frame"]))
    varr_min = varr_ref.min("frame").compute()
    varr_ref = varr_ref - varr_min
    varr_ref = denoise(varr_ref, **PARAM_DENOISE)
    varr_ref = remove_background(varr_ref, **PARAM_BACKGROUND_REMOVAL)
    Y = apply_transform(varr_ref, motion.chunk({"frame": frame_chunk}), fill=0)
    # The notebook saves `Y_fm_chk = Y.astype(float)` and feeds that to
    # compute_trace, so the cast happens before the trace, not inside it.
    return Y.astype(float).rename("Y")


