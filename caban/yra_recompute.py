def _per_cell_correlation(left: np.ndarray, right: np.ndarray) -> np.ndarray:
    """Pearson r between matching rows of two (unit, frame) matrices."""
    lc = left - left.mean(axis=1, keepdims=True)
    rc = right - right.mean(axis=1, keepdims=True)
    denom = np.linalg.norm(lc, axis=1) * np.linalg.norm(rc, axis=1)
    corr = np.full(left.shape[0], np.nan)
    good = denom > 0
    corr[good] = (lc[good] * rc[good]).sum(axis=1) / denom[good]
    return corr


def _summary(values: np.ndarray) -> dict:
    finite = values[np.isfinite(values)]
    if finite.size == 0:
        return {"n": 0, "n_undefined": int(values.size)}
    return {
        "n": int(finite.size),
        "n_undefined": int(values.size - finite.size),
        "median": float(np.median(finite)),
        "p5": float(np.percentile(finite, 5)),
        "p95": float(np.percentile(finite, 95)),
        "min": float(finite.min()),
    }


def footprint_overlap_ratio(A: xr.DataArray) -> np.ndarray:
    """Per unit, the mass of its footprint's overlap with *other* footprints.

    ``sum_{j != i} <A_i, A_j> / <A_i, A_i>``, the coefficient by which other units'
    traces enter ``YrA_i``.  In ``compute_trace`` the ``j == i`` term cancels
    ``C_i`` exactly, so this ratio is the whole of ``YrA_i``'s dependence on ``C``:
    a unit with ratio 0 has ``YrA_i = <Ybs, A_i> / <A_i, A_i>``, a function of the
    movie and its own footprint alone.

    That makes it the key to reading the comparison against the exported
    ``YrA.zarr``.  The export was computed from the ``C`` that existed *before* the
    second temporal update, and from that run's own footprints, while the ``C`` and
    ``A`` on disk are a different run's.  Disagreement that rises with this ratio
    is that known difference; disagreement at ratio 0 would mean the replay itself
    is wrong.
    """
    footprints = darr.from_array(A.data.map_blocks(sparse.COO).compute(), chunks=-1)
    AtA = darr.tensordot(footprints, footprints, axes=[(1, 2), (1, 2)]).compute()
    AtA = np.asarray(AtA.todense() if hasattr(AtA, "todense") else AtA)
    diagonal = np.diag(AtA).copy()
    off_diagonal = AtA.copy()
    np.fill_diagonal(off_diagonal, 0.0)
    return off_diagonal.sum(axis=1) / diagonal


def check_and_report(
    YrA_new: xr.DataArray,
    S_unit_id: np.ndarray,
    C: xr.DataArray,
    YrA_old: Optional[xr.DataArray],
    del_frames_derived: list,
    del_frames_notebook: list,
    overlap_ratio: np.ndarray,
) -> dict:
    """Run the hard assertions and build the review report of the plan's 11.6.

    Hard failures (this function raises): ``del_frames`` disagreement, a
    ``unit_id`` that is not ``S``'s elementwise, a shape or ``frame`` mismatch
    against ``C``, or any NaN/inf in the output.  Everything else is reported for
    the reader to judge.

    ``YrA_old`` is ``None`` for the 102 of 130 sessions that never had a ``YrA``
    exported -- the recall sessions of plan 11.7 step 4 and most of the LT
    sessions.  Those lean on the hard checks and on ``corr(C, YrA_new)``; the
    comparison block is then absent from the report rather than faked.
    """
    if list(del_frames_derived) != list(del_frames_notebook):
        raise ValueError(
            "del_frames disagree.\n"
            "  derived from the saved frame coordinate: {}\n"
            "  recorded in the pipeline notebook:       {}".format(
                del_frames_derived, del_frames_notebook
            )
        )

    new_ids = np.asarray(YrA_new.coords["unit_id"].values)
    S_unit_id = np.asarray(S_unit_id)
    if not np.array_equal(new_ids, S_unit_id):
        raise ValueError(
            "recomputed unit_id is not S's unit_id elementwise: {} of {} positions "
            "differ".format(int((new_ids != S_unit_id).sum()) if new_ids.shape == S_unit_id.shape
                            else "shape", len(S_unit_id))
        )
    if YrA_new.shape != C.shape:
        raise ValueError(
            "recomputed YrA has shape {} but C has shape {}".format(YrA_new.shape, C.shape)
        )
    if not np.array_equal(YrA_new.frame.values, C.frame.values):
        raise ValueError("recomputed YrA frame coordinate differs from C's")

    new = np.asarray(YrA_new.values)
    if not np.isfinite(new).all():
        n_nan = int(np.isnan(new).sum())
        n_inf = int(np.isinf(new).sum())
        raise ValueError(
            "recomputed YrA contains {} NaN and {} inf values".format(n_nan, n_inf)
        )

    C_values = np.asarray(C.values)
    floor_per_cell = (new == 0).mean(axis=1)
    report = {
        "del_frames": {
            "derived_from_frame_coord": list(del_frames_derived),
            "from_notebook": list(del_frames_notebook),
            "agree": True,
        },
        "n_units": int(len(new_ids)),
        "n_frames": int(YrA_new.sizes["frame"]),
        "corr_C_vs_new": _summary(_per_cell_correlation(new, C_values)),
        "clip_floor_fraction": {
            "overall": float((new == 0).mean()),
            "per_cell": _summary(floor_per_cell),
        },
        "vs_old_YrA": None,
    }
    if YrA_old is None:
        return report

    old_ids = np.asarray(YrA_old.coords["unit_id"].values)
    old_pos = {int(u): i for i, u in enumerate(old_ids)}
    shared = [int(u) for u in new_ids if int(u) in old_pos]
    new_rows = np.array([int(np.flatnonzero(new_ids == u)[0]) for u in shared], dtype=int)
    old_rows = np.array([old_pos[u] for u in shared], dtype=int)
    old = np.asarray(YrA_old.values)[old_rows]

    corr_vs_old = _per_cell_correlation(new[new_rows], old)
    abs_diff = np.abs(new[new_rows] - old)
    disagreeing = [
        {
            "unit_id": int(u),
            "corr": float(corr_vs_old[k]),
            "max_abs_diff": float(abs_diff[k].max()),
        }
        for k, u in enumerate(shared)
        if not (corr_vs_old[k] > 0.999)
    ]
    disagreeing.sort(key=lambda d: d["corr"])

    overlap_shared = np.asarray(overlap_ratio)[new_rows]
    by_overlap = []
    for low, high, label in (
        (-np.inf, 0.0, "none"),
        (0.0, 0.01, "0-1%"),
        (0.01, 0.10, "1-10%"),
        (0.10, np.inf, ">10%"),
    ):
        selected = (overlap_shared > low) & (overlap_shared <= high)
        if low == -np.inf:
            selected = overlap_shared <= 0
        if not selected.any():
            continue
        entry = {"overlap": label, "n_units": int(selected.sum())}
        entry.update(_summary(corr_vs_old[selected]))
        by_overlap.append(entry)

    report["vs_old_YrA"] = {
        "n_shared_units": len(shared),
        "unit_ids_new_only": sorted(set(new_ids.tolist()) - set(old_ids.tolist())),
        "unit_ids_old_only": sorted(set(old_ids.tolist()) - set(new_ids.tolist())),
        "corr": _summary(corr_vs_old),
        "max_abs_diff": float(abs_diff.max()),
        "n_units_below_r_0.999": len(disagreeing),
        "units_below_r_0.999": disagreeing[:50],
        "corr_by_footprint_overlap": by_overlap,
    }
    return report


def format_report(report: dict) -> str:
    """Render :func:`check_and_report`'s output for printing between sessions."""
    lines = []
    dl = report["del_frames"]
    lines.append("del_frames")
    lines.append("  derived from frame coord : {}".format(dl["derived_from_frame_coord"] or "[] (none dropped)"))
    lines.append("  from pipeline notebook   : {}".format(dl["from_notebook"] or "[] (none dropped)"))
    lines.append("")
    lines.append("recomputed YrA: {} units x {} frames".format(report["n_units"], report["n_frames"]))
    c = report["corr_C_vs_new"]
    lines.append("  corr(C, YrA_new) per cell : median {:.3f}  p5 {:.3f}  p95 {:.3f}".format(
        c["median"], c["p5"], c["p95"]))
    fl = report["clip_floor_fraction"]
    lines.append("  clip(0) floor             : {:.4f} of all samples; per cell median {:.4f}, p95 {:.4f}".format(
        fl["overall"], fl["per_cell"]["median"], fl["per_cell"]["p95"]))
    lines.append("")
    vo = report["vs_old_YrA"]
    if vo is None:
        lines.append("no YrA.zarr was ever exported for this session, so there is nothing to")
        lines.append("compare against; the hard checks above are what stand behind this one.")
        return "\n".join(lines)
    lines.append("against the existing YrA.zarr, matched by unit id")
    lines.append("  shared units              : {}".format(vo["n_shared_units"]))
    lines.append("  in new only               : {}".format(vo["unit_ids_new_only"] or "[]"))
    lines.append("  in old only               : {}".format(vo["unit_ids_old_only"] or "[]"))
    lines.append("  per-cell corr             : median {:.6f}  p5 {:.6f}  min {:.6f}".format(
        vo["corr"]["median"], vo["corr"]["p5"], vo["corr"]["min"]))
    lines.append("  max abs diff              : {:.6g}".format(vo["max_abs_diff"]))
    lines.append("  units with r <= 0.999     : {}".format(vo["n_units_below_r_0.999"]))
    lines.append("")
    lines.append("  per-cell corr split by footprint overlap -- the export used a different run's")
    lines.append("  C and footprints, and C reaches YrA_i only through overlapping units, so")
    lines.append("  agreement at zero overlap is what validates the replay:")
    for entry in vo["corr_by_footprint_overlap"]:
        lines.append("      overlap {:>5}  n = {:>4}  median r = {:.9f}  p5 {:.6f}  min {:.6f}".format(
            entry["overlap"], entry["n_units"], entry["median"], entry["p5"], entry["min"]))
    for entry in vo["units_below_r_0.999"]:
        lines.append("      unit {:>5}  r = {:.6f}  max|diff| = {:.6g}".format(
            entry["unit_id"], entry["corr"], entry["max_abs_diff"]))
    return "\n".join(lines)


def compare_replayed_movie(Y_new: xr.DataArray, saved_movie_path: str, n_frames: int = 50) -> dict:
    """Compare the replayed ``Y`` against a saved ``Y_fm_chk.zarr``, on a frame sample.

    This is step (1) of the plan's 7.1 gate, and it exists for exactly one session:
    G10's conditioning session is the only one whose ``minian_intermediate/`` was
    kept.  Comparing a sample rather than the whole movie keeps the check to one
    extra pass over a few hundred MB instead of 77 GB.
    """
    saved = xr.open_zarr(saved_movie_path, consolidated=False)["Y_fm_chk"]
    if not np.array_equal(Y_new.frame.values, saved.frame.values):
        raise ValueError("replayed Y and saved Y_fm_chk have different frame coordinates")
    idx = np.unique(np.linspace(0, Y_new.sizes["frame"] - 1, n_frames).astype(int))
    a = Y_new.isel(frame=idx).values
    b = saved.isel(frame=idx).values
    diff = np.abs(a - b)
    return {
        "n_frames_compared": int(len(idx)),
        "exactly_equal": bool(np.array_equal(a, b)),
        "max_abs_diff": float(diff.max()),
        "mean_abs_diff": float(diff.mean()),
        "n_pixels_differing": int((diff > 0).sum()),
    }


